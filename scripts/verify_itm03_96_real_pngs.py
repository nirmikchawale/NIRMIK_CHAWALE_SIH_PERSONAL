#!/usr/bin/env python3
"""Fail-closed validation of persisted ITM-03 real Chromium theme screenshots.

Reads the exact real files generated by Playwright, not placeholder images.
Never creates screenshots or invents scientific evidence.
"""
from __future__ import annotations
import hashlib
import json
import re
import struct
import sys
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EVIDENCE = ROOT / "frontend" / "certification-evidence" / "itm03-mpr16"
SIZES = {"wide-desktop": (1440, 900), "tablet": (768, 900), "mobile": (390, 844)}
VIEWS = ("geographic", "water-column")
PNG_SIG = b"\x89PNG\r\n\x1a\n"


def canonical_themes() -> list[str]:
    source = (ROOT / "frontend" / "src" / "theme.ts").read_text("utf-8")
    match = re.search(r"export const GLASS_THEMES:.*?=\s*\[(.*?)\]\s*as const;", source, re.S)
    if not match:
        raise RuntimeError("Canonical GLASS_THEMES definition not found")
    themes = re.findall(r'\bid:\s*"([a-z0-9-]+)"', match.group(1))
    if len(themes) != 16 or len(set(themes)) != 16:
        raise RuntimeError("Canonical theme list must contain exactly 16 different IDs")
    return themes


def png_dimensions_and_integrity(raw: bytes) -> tuple[int, int]:
    if not raw.startswith(PNG_SIG) or len(raw) < 1024:
        raise RuntimeError("Screenshot is missing, truncated, or not a real-sized PNG")
    offset = len(PNG_SIG)
    dimensions = None
    seen_end = False
    while offset < len(raw):
        if offset + 12 > len(raw):
            raise RuntimeError("PNG missing complete chunk")
        length = struct.unpack_from(">I", raw, offset)[0]
        if length > 20_000_000 or offset + 12 + length > len(raw):
            raise RuntimeError("PNG invalid or oversized chunk")
        kind = raw[offset + 4: offset + 8]
        payload = raw[offset + 8: offset + 8 + length]
        actual_crc = struct.unpack_from(">I", raw, offset + 8 + length)[0]
        if zlib.crc32(kind + payload) & 0xFFFFFFFF != actual_crc:
            raise RuntimeError("Screenshot PNG chunk CRC mismatch")
        if kind == b"IHDR":
            if dimensions is not None or length != 13:
                raise RuntimeError("PNG invalid IHDR")
            dimensions = struct.unpack_from(">II", payload)
        if kind == b"IEND":
            if length != 0 or offset + 12 != len(raw):
                raise RuntimeError("PNG missing final IEND")
            seen_end = True
            break
        offset += 12 + length
    if not seen_end or dimensions is None:
        raise RuntimeError("PNG missing IHDR or IEND")
    return dimensions


def verify() -> dict:
    themes = canonical_themes()
    directory = EVIDENCE / "screenshots"
    expected = {f"{viewport}--{theme}--{view}.png": dimensions
                for viewport, dimensions in SIZES.items()
                for theme in themes for view in VIEWS}
    available = {p.name for p in directory.glob("*.png")} if directory.is_dir() else set()
    if available != set(expected):
        raise RuntimeError(f"Expected 96 original PNG files; found {len(available)}, "
                           f"missing={sorted(set(expected)-available)[:8]}, "
                           f"unexpected={sorted(available-set(expected))[:8]}")
    entries = []
    checksums = set()
    for name, dimensions in sorted(expected.items()):
        raw = (directory / name).read_bytes()
        got = png_dimensions_and_integrity(raw)
        if got != dimensions:
            raise RuntimeError(f"Viewport pixels mismatch: {name}, {got} != {dimensions}")
        digest = hashlib.sha256(raw).hexdigest()
        if digest in checksums:
            raise RuntimeError(f"Duplicate screenshot pixels in {name}")
        checksums.add(digest)
        entries.append({"path": f"screenshots/{name}", "sha256": digest,
                        "bytes": len(raw), "dimensions": list(got)})
    return {"source": "real Chromium Playwright page.screenshot persisted PNG",
            "synthetic_images": False, "count": len(entries), "theme_count": len(themes),
            "viewports": SIZES, "views": VIEWS, "files": entries}


def main() -> int:
    try:
        result = verify()
        EVIDENCE.mkdir(parents=True, exist_ok=True)
        path = EVIDENCE / "ITM03_96_REAL_PNG_MANIFEST.json"
        path.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
        print(f"PASS: {result['count']} unique, CRC-verified real Chromium PNG images; {path}")
        return 0
    except (OSError, ValueError, RuntimeError) as e:
        print(f"FAIL CLOSED: ITM-03 retained Chromium evidence: {e}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
